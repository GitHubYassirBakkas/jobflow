CREATE TABLE saved_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    candidate_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    saved_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_saved_jobs PRIMARY KEY (id),
    CONSTRAINT uq_saved_jobs_candidate_job UNIQUE (candidate_id, job_id),
    CONSTRAINT fk_saved_jobs_candidate FOREIGN KEY (candidate_id) REFERENCES users (id),
    CONSTRAINT fk_saved_jobs_job FOREIGN KEY (job_id) REFERENCES jobs (id)
);

CREATE INDEX idx_saved_jobs_candidate_saved_at_id
    ON saved_jobs (candidate_id, saved_at DESC, id DESC);
