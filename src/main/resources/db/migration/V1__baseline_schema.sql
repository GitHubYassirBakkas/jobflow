CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    email VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CANDIDATE', 'RECRUITER', 'ADMIN'))
);

CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(2000),
    location VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    website VARCHAR(255),
    CONSTRAINT pk_companies PRIMARY KEY (id)
);

CREATE TABLE candidate_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    bio VARCHAR(2000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    location VARCHAR(255),
    phone VARCHAR(255),
    skills VARCHAR(1000),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    cv_file_name VARCHAR(255),
    cv_file_path VARCHAR(255),
    CONSTRAINT pk_candidate_profiles PRIMARY KEY (id),
    CONSTRAINT uq_candidate_profiles_user_id UNIQUE (user_id),
    CONSTRAINT fk_candidate_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE recruiter_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    job_title VARCHAR(255),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    company_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT pk_recruiter_profiles PRIMARY KEY (id),
    CONSTRAINT uq_recruiter_profiles_user_id UNIQUE (user_id),
    CONSTRAINT fk_recruiter_profiles_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_recruiter_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(5000) NOT NULL,
    employment_type VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    company_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_jobs_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_jobs_employment_type CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'INTERNSHIP', 'CONTRACT', 'FREELANCE'))
);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    applied_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    candidate_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL,
    cv_file_name VARCHAR(255),
    cv_file_path VARCHAR(255),
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT uq_applications_candidate_job UNIQUE (candidate_id, job_id),
    CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_id) REFERENCES users (id),
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT ck_applications_status CHECK (status IN ('APPLIED', 'REVIEWING', 'INTERVIEW', 'ACCEPTED', 'REJECTED'))
);

CREATE TABLE interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    location VARCHAR(255),
    meeting_link VARCHAR(255),
    notes VARCHAR(2000),
    scheduled_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    application_id BIGINT NOT NULL,
    CONSTRAINT pk_interviews PRIMARY KEY (id),
    CONSTRAINT uq_interviews_application_id UNIQUE (application_id),
    CONSTRAINT fk_interviews_application FOREIGN KEY (application_id) REFERENCES applications (id),
    CONSTRAINT ck_interviews_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_interviews_type CHECK (type IN ('ONLINE', 'ONSITE', 'PHONE'))
);
