CREATE TABLE application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    changed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    changed_by BIGINT,
    changed_by_role VARCHAR(255),
    event_type VARCHAR(32) NOT NULL,
    CONSTRAINT pk_application_status_history PRIMARY KEY (id),
    CONSTRAINT fk_application_status_history_application FOREIGN KEY (application_id) REFERENCES applications (id),
    CONSTRAINT fk_application_status_history_changed_by FOREIGN KEY (changed_by) REFERENCES users (id),
    CONSTRAINT ck_application_status_history_status CHECK (status IN ('APPLIED', 'REVIEWING', 'INTERVIEW', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_application_status_history_changed_by_role CHECK (changed_by_role IS NULL OR changed_by_role IN ('CANDIDATE', 'RECRUITER', 'ADMIN')),
    CONSTRAINT ck_application_status_history_event_type CHECK (event_type IN ('BASELINE', 'TRANSITION'))
);

CREATE INDEX idx_application_status_history_application_changed_at_id
    ON application_status_history (application_id, changed_at ASC, id ASC);

INSERT INTO application_status_history (
    application_id,
    status,
    changed_at,
    changed_by,
    changed_by_role,
    event_type
)
SELECT
    id,
    status,
    CURRENT_TIMESTAMP,
    NULL,
    NULL,
    'BASELINE'
FROM applications;
